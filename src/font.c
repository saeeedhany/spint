static SDL_Texture *atlas;

bool font_init(SDL_Renderer *r)
{
    static uint32_t px[CELL_H][GLYPHS * CELL_W];
    memset(px, 0, sizeof px);
    for (int g = 0; g < GLYPHS; g++)
        for (int y = 0; y < CELL_H; y++)
            for (int x = 0; x < 5; x++)
                if (glyphs[g][y] & (0x10 >> x)) px[y][g * CELL_W + x] = 0xFFFFFFFFu;
    atlas = SDL_CreateTexture(r, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STATIC, GLYPHS * CELL_W, CELL_H);
    if (!atlas) return false;
    SDL_UpdateTexture(atlas, NULL, px, GLYPHS * CELL_W * sizeof(uint32_t));
    SDL_SetTextureBlendMode(atlas, SDL_BLENDMODE_BLEND);
    SDL_SetTextureScaleMode(atlas, SDL_ScaleModeNearest);
    return true;
}

void font_free(void)
{
    if (atlas) SDL_DestroyTexture(atlas);
    atlas = NULL;
}

int font_width(const char *text)
{
    int n = (int)strlen(text);
    return n ? n * FONT_ADVANCE - FONT_SCALE : 0;
}

void font_draw(SDL_Renderer *r, int x, int y, const char *text, uint32_t color)
{
    SDL_SetTextureColorMod(atlas, (color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF);
    SDL_SetTextureAlphaMod(atlas, (color >> 24) & 0xFF);
    for (const unsigned char *p = (const unsigned char *)text; *p; p++, x += FONT_ADVANCE) {
        int c = *p;
        if (c < FIRST || c > LAST) c = '?';
        if (c == ' ') continue;
        SDL_Rect src = { (c - FIRST) * CELL_W, 0, 5, CELL_H };
        SDL_Rect dst = { x, y, 5 * FONT_SCALE, CELL_H * FONT_SCALE };
        SDL_RenderCopy(r, atlas, &src, &dst);
    }
}
